BRIEF = """# Vision pass brief — {title}

You are the vision model for a footy breakdown. Look at the contact sheets and grid
frames below, then edit `{moments}`. Do not render anything.

## For each candidate (in `candidates`)
- `visible`: one or two plain sentences of what the frames show. Only what is visible.
- `why`: why it might be worth a coach's comment (positioning, spacing, contest,
  decision, technique) or why not.
- `vision_rank`: your ranking (1 = best teaching moment). `status`: chosen / dropped,
  with `drop_reason` when dropped (no clear teaching point is a valid reason).
- The cheap signals only say where to look. Say so when they misfired.

## For each chosen candidate, add a moment (in `moments`)
- `in_f`, `freeze_f`, `out_f`: the lead-in, the exact frame to freeze on, the outcome.
  Get exact frames with `python -m studio.footy frames {moments} --clip <id> --at f1,f2,...`.
- `claims`: every statement you make, each with `confidence`:
  `seen` (plainly visible), `likely` (a reasonable reading), `unsure` (cannot confirm),
  and the `frames` that show it.
- `cannot_tell`: what the footage does not show (off-screen players, camera angle,
  depth, the umpire's view, the score, who anyone is…).
- Never invent players, names, jumper numbers, scores, teams or rules. Refer to players
  by what is visible ("the defender in the dark jumper", "the leading forward").
- `teaching_point` in coaching terms; if there is none, set `status: drop` with a reason.
- `captions`: `watch` (optional lead-in), up to 3 short `freeze` sentences, an `outcome`
  line. Calm coach voice: short sentences, no hype, no exclamation marks. Each caption
  lists the claims it rests on; never an `unsure` one.
- `tracks` (video px of the proxy, keyed by proxy frame; `point: feet` for rings) and
  `annotations` (ring, spotlight, arrow, line, zone, label). Read positions off the grid
  frames. Mark anything you are not sure of with `adjust: true` and a `note`.

Then run `python -m studio.footy check {moments}` and fix every error. Stop there: the
user approves before anything renders.

## Material
{material}
"""


def _slug_dir(moments_path: Path) -> Path:
    return Path(moments_path).resolve().parent


def _relmedia(p: Path) -> str:
    return paths.rel(p)


def _blank(title: str) -> dict:
    return M.MomentsFile(title=title).model_dump(by_alias=True, mode="json")


def _tc(seconds: float) -> str:
    h, rem = divmod(seconds, 3600)
    m, s = divmod(rem, 60)
    return f"{int(h):02d}:{int(m):02d}:{s:06.3f}"


def _parse_tc(s: str | None) -> float | None:
    if s is None:
        return None
    if re.match(r"^\d+(\.\d+)?$", s):
        return float(s)
    parts = [float(x) for x in s.split(":")]
    while len(parts) < 3:
        parts.insert(0, 0.0)
    return parts[0] * 3600 + parts[1] * 60 + parts[2]


def cmd_placeholder(a) -> int:
    from . import placeholder
    folder = BASE / "placeholder"
    src = placeholder.make(folder)
    print(f"placeholder source: {paths.rel(src)}  (synthetic, labelled PLACEHOLDER in every frame)")
    a2 = argparse.Namespace(file=str(src), slug="placeholder", clip_id="c1", t_in=None, t_out=None, url=None,
                            competition="PLACEHOLDER (synthetic test clip)", match="none — synthetic", date=None,
                            broadcaster=None, rights="placeholder", notes="Generated by studio/footy/placeholder.py; not real footage.",
                            title="Placeholder breakdown", placeholder=True, max_width=1920)
    return cmd_ingest(a2)


def cmd_ingest(a) -> int:
    src = Path(a.file).resolve()
    if not src.is_file():
        print(f"no such file: {a.file}\nThis pipeline does not download. Save the clip yourself into {paths.rel(BASE)}/ "
              "(only if you have the right to use it) and pass the file; give the link with --url so it is logged.")
        return 2
    try:
        src.relative_to(BASE.resolve())
    except ValueError:
        print(f"note: {paths.rel(src)} is outside {paths.rel(BASE)}/ — keeping source footage there keeps it git-ignored and together.")
    slug = a.slug
    folder = BASE / slug
    mpath = folder / "moments.json"
    data = M.load(mpath) if mpath.is_file() else _blank(a.title or slug)
    t_in, t_out = _parse_tc(a.t_in), _parse_tc(a.t_out)
    proxy = folder / "clips" / f"{a.clip_id}.mp4"
    info = media.probe(src)
    print(f"source: {info['width']}x{info['height']} @ {info['fps_float']:.3f} fps ({'VFR' if info['vfr'] else 'CFR'}), {info['duration']:.2f} s")
    p = media.make_proxy(src, proxy, t_in, t_out, max_width=a.max_width)
    fps = media.fps_json(p["fps"])
    print(f"proxy:  {paths.rel(proxy)}  {p['width']}x{p['height']} @ {float(p['fps']):.3f} fps CFR all-intra, {p['frames']} frames")
    seg_in = t_in or 0.0
    seg_out = t_out if t_out is not None else info["duration"]
    clip = {
        "id": a.clip_id, "proxy": _relmedia(proxy), "fps": fps, "frames": p["frames"], "width": p["width"], "height": p["height"],
        "audio": p["audio"], "audio_file": _relmedia(p["audio_file"]) if p["audio_file"] else None,
        "placeholder": bool(getattr(a, "placeholder", False)),
        "source": {"kind": "placeholder" if getattr(a, "placeholder", False) else ("link" if a.url else "file"),
                   "url": a.url, "file": _relmedia(src), "competition": a.competition, "match": a.match, "date": a.date,
                   "broadcaster": a.broadcaster, "time_range": {"in": _tc(seg_in), "out": _tc(seg_out)},
                   "rights": a.rights, "notes": a.notes or ""},
    }
    data["clips"] = [c for c in data.get("clips", []) if c["id"] != a.clip_id] + [clip]
    M.parse(data)
    folder.mkdir(parents=True, exist_ok=True)
    M.save(mpath, data)
    print(f"logged clip {a.clip_id} in {paths.rel(mpath)}")
    if (seg_out - seg_in) > 45:
        print("warning: clip is longer than 45 s — trim to the moment plus its lead-in and outcome (--in/--out)")
    return 0


def cmd_scan(a) -> int:
    mpath = Path(a.moments)
    data = M.load(mpath)
    mf = M.parse(data)
    folder = _slug_dir(mpath) / "scan"
    folder.mkdir(parents=True, exist_ok=True)
    keep_vision = {c["id"]: c for c in data.get("candidates", [])}
    new_cands = [c for c in data.get("candidates", []) if a.clip and c["clip"] != a.clip]
    material = []
    for c in mf.clips:
        if a.clip and c.id != a.clip:
            continue
        proxy = paths.ROOT / c.proxy
        print(f"scanning {c.id} ({c.frames} frames)…")
        sig = signals.compute(proxy, c.fps, c.width, paths.ROOT / c.audio_file if c.audio_file else None)
        cuts, shot_list = signals.shots(sig, c.fps)
        score, cands = signals.candidates(sig, c.fps, shot_list, cuts, max_n=a.max)
        strip = sheets.signal_strip(sig, score, cuts, cands, c.fps, folder / f"{c.id}-signals.png")
        material.append(f"- `{paths.rel(strip)}` — signals over the whole clip (cuts blue, transitions orange, candidates shaded)")
        for cd in cands:
            frames = sorted(set(int(x) for x in np.linspace(cd["start_f"], cd["end_f"], 12).round()) | {cd["peak_f"]})
            imgs = media.extract_frames(proxy, frames, c.fps)
            sheet = sheets.contact_sheet(imgs, c.fps, folder / f"{c.id}-{cd['id']}-sheet.png",
                                         f"{c.id} {cd['id']} rank {cd['rank']}  f{cd['start_f']}-f{cd['end_f']}  peak f{cd['peak_f']}"
                                         + ("  REPLAY?" if cd["replay_suspect"] else ""))
            grid = sheets.grid_frame(imgs[cd["peak_f"]], cd["peak_f"], c.fps, folder / f"{c.id}-{cd['id']}-grid-f{cd['peak_f']:05d}.png")
            cd["id"] = f"{c.id}-{cd['id']}"
            cd["clip"] = c.id
            cd["sheet"] = paths.rel(sheet)
            old = keep_vision.get(cd["id"])
            if old and old.get("start_f") == cd["start_f"] and old.get("end_f") == cd["end_f"]:
                for k in ("visible", "why", "vision_rank", "status", "drop_reason"):
                    cd[k] = old.get(k, cd.get(k))
            new_cands.append(cd)
            sig_txt = "; ".join(f"{s['signal']} f{s['frame']}" for s in cd["signals"]) or "weak signals only"
            material.append(f"- `{paths.rel(sheet)}` and `{paths.rel(grid)}` — {cd['id']}: f{cd['start_f']}–f{cd['end_f']}, peak f{cd['peak_f']} ({sig_txt})")
            print(f"  {cd['id']}: f{cd['start_f']}-f{cd['end_f']} peak f{cd['peak_f']} score {cd['score']}  {sig_txt}")
        summary = {"clip": c.id, "fps": c.fps, "frames": c.frames, "cuts": cuts, "shots": shot_list,
                   "has_audio": sig["has_audio"], "candidates": [x["id"] for x in cands]}
        (folder / f"{c.id}-scan.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    data["candidates"] = new_cands
    M.save(mpath, data)
    brief = folder / "brief.md"
    brief.write_text(BRIEF.format(title=mf.title, moments=paths.rel(mpath), material="\n".join(material)), encoding="utf-8")
    print(f"wrote {len(new_cands)} candidates to {paths.rel(mpath)}; vision brief: {paths.rel(brief)}")
    return 0


def cmd_frames(a) -> int:
    mpath = Path(a.moments)
    mf = M.parse(M.load(mpath))
    c = next((x for x in mf.clips if x.id == a.clip), None)
    if not c:
        print(f"unknown clip {a.clip}")
        return 2
    want = [int(x) for x in re.split(r"[,\s]+", a.at.strip()) if x]
    imgs = media.extract_frames(paths.ROOT / c.proxy, want, c.fps)
    folder = _slug_dir(mpath) / "scan" / "frames"
    for f, im in imgs.items():
        out = folder / f"{c.id}-f{f:05d}{'-grid' if a.grid else ''}.png"
        if a.grid:
            sheets.grid_frame(im, f, c.fps, out, step=a.step)
        else:
            folder.mkdir(parents=True, exist_ok=True)
            im.save(out)
        print(paths.rel(out))
    return 0


def cmd_check(a) -> int:
    from .build import node
    mpath = Path(a.moments)
    data = M.load(mpath)
    errors, warns, mf = M.check(data)
    proofs = {}
    if not a.no_proofs and not errors:
        clips = {c.id: c for c in mf.clips}
        kept = [m for m in mf.moments if m.status == "keep"]
        if kept:
            pts = node("sample", {"moments": [m.model_dump(by_alias=True, exclude_none=True) for m in kept]})["points"]
            for m in kept:
                c = clips[m.clip]
                img = media.extract_frames(paths.ROOT / c.proxy, [m.freeze_f], c.fps)[m.freeze_f]
                per = pts.get(m.id, {})

                def sample(tid, f, per=per):
                    v = per.get(tid, {}).get(str(f))
                    return None if v is None else (v[0], v[1])
                out = sheets.proof(img, m.model_dump(by_alias=True, exclude_none=True), _slug_dir(mpath) / "proofs" / f"{m.id}-f{m.freeze_f:05d}.png", sample)
                proofs[m.id] = paths.rel(out).replace(paths.rel(_slug_dir(mpath)) + "/", "")
    if data.get("review", {}).get("status") == "draft" and not errors and mf.moments:
        data["review"]["status"] = "proposed"
        M.save(mpath, data)
    md = M.summary(data, errors, warns, proofs, _slug_dir(mpath))
    mdp = mpath.with_suffix(".md")
    mdp.write_text(md, encoding="utf-8")
    for e in errors:
        print(f"ERROR  {e}")
    for w in warns:
        print(f"check  {w}")
    print(f"{len(errors)} errors, {len(warns)} to check — summary: {paths.rel(mdp)}")
    return 1 if errors else 0


def cmd_approve(a) -> int:
    try:
        rv = M.approve(Path(a.moments), a.by, a.notes or "")
    except ValueError as e:
        print(e)
        return 1
    print(f"approved by {rv['by']} at {rv['at']} (hash {rv['hash'][:12]}…). Any edit to the file voids this.")
    return 0


def cmd_build(a) -> int:
    from .build import build
    try:
        out = build(Path(a.moments), Path(a.project) if a.project else None)
    except PermissionError as e:
        print(f"REFUSED: {e}")
        return 3
    print(f"wrote {paths.rel(out)} — render with:\n  render.bat {paths.rel(out)} --preset vertical\n  render.bat {paths.rel(out)} --preset 1080p30")
    return 0


def cmd_verify(a) -> int:
    from .verify import verify
    res = verify(Path(a.render), Path(a.project))
    print(json.dumps(res, indent=1))
    return 0 if res["ok"] else 1


def main(argv=None) -> int:
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
    ap = argparse.ArgumentParser(prog="python -m studio.footy", description="Footy breakdown pipeline")
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("placeholder", help="make + ingest the synthetic placeholder clip")
    s.set_defaults(fn=cmd_placeholder)
    s = sub.add_parser("ingest", help="trim + proxy a clip you supplied, and log its source")
    s.add_argument("file")
    s.add_argument("--slug", required=True, help="folder name under media/afl-breakdown/")
    s.add_argument("--clip-id", default="c1")
    s.add_argument("--in", dest="t_in", help="start in the file (HH:MM:SS.mmm or seconds)")
    s.add_argument("--out", dest="t_out", help="end in the file")
    s.add_argument("--url", help="where the footage came from (logged, never fetched)")
    s.add_argument("--competition", required=True)
    s.add_argument("--match", help="as named by the source, e.g. 'Round 5, Team v Team'")
    s.add_argument("--date", help="match date YYYY-MM-DD")
    s.add_argument("--broadcaster")
    s.add_argument("--rights", default="unchecked", choices=["unchecked", "cleared", "own"])
    s.add_argument("--notes")
    s.add_argument("--title", help="breakdown title (new moments file only)")
    s.add_argument("--max-width", type=int, default=1920)
    s.set_defaults(fn=cmd_ingest, placeholder=False)
    s = sub.add_parser("scan", help="cheap signals → ranked candidates, contact sheets, vision brief")
    s.add_argument("moments")
    s.add_argument("--clip")
    s.add_argument("--max", type=int, default=6)
    s.set_defaults(fn=cmd_scan)
    s = sub.add_parser("frames", help="exact proxy frames (with a video-px grid) for placing annotations")
    s.add_argument("moments")
    s.add_argument("--clip", required=True)
    s.add_argument("--at", required=True, help="frames, e.g. 96,120,146")
    s.add_argument("--grid", action="store_true")
    s.add_argument("--step", type=int, default=50)
    s.set_defaults(fn=cmd_frames)
    s = sub.add_parser("check", help="validate the analysis; write moments.md and proof stills")
    s.add_argument("moments")
    s.add_argument("--no-proofs", action="store_true")
    s.set_defaults(fn=cmd_check)
    s = sub.add_parser("approve", help="record your approval (required before build)")
    s.add_argument("moments")
    s.add_argument("--by", required=True)
    s.add_argument("--notes")
    s.set_defaults(fn=cmd_approve)
    s = sub.add_parser("build", help="approved moments → project JSON")
    s.add_argument("moments")
    s.add_argument("--project")
    s.set_defaults(fn=cmd_build)
    s = sub.add_parser("verify", help="check freezes landed on their exact frames in a render")
    s.add_argument("render")
    s.add_argument("--project", default=str(paths.PROJECTS / "afl-breakdown.json"))
    s.set_defaults(fn=cmd_verify)
    a = ap.parse_args(argv)
    return a.fn(a)


if __name__ == "__main__":
    sys.exit(main())

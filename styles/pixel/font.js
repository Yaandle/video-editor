const ALIAS = { '—': '-', '–': '-', '·': '.', '’': "'", '‘': "'", '“': '"', '”': '"', '…': '.' };

const CACHE = new Map();
export const CAP = 7;          // cap height in font pixels
export const LINE = 10;        // line advance in font pixels (incl. descenders + gap)

/** Glyph as { w, rows: [[0|1…]] } (unknown characters render as '?'). */
export function glyph(ch) {
  const c = G[ch] !== undefined ? ch : ALIAS[ch] ?? (G[ch.toUpperCase?.()] ? ch.toUpperCase() : '?');
  if (!CACHE.has(c)) {
    const rows = G[c].split('|').map((r) => [...r].map((x) => (x === '#' ? 1 : 0)));
    CACHE.set(c, { w: rows[0].length, rows });
  }
  return CACHE.get(c);
}

/** Width in font pixels of a string (advance = glyph width + 1, last gap dropped). */
export function measure(text) {
  let w = 0;
  for (const ch of text) w += glyph(ch).w + 1;
  return Math.max(0, w - 1);
}

/** Word-wrap to `maxW` font pixels; '\n' forces a break. */
export function wrap(text, maxW) {
  const out = [];
  for (const para of String(text).split('\n')) {
    let line = '';
    for (const word of para.split(/\s+/).filter(Boolean)) {
      const next = line ? `${line} ${word}` : word;
      if (line && measure(next) > maxW) { out.push(line); line = word; } else line = next;
    }
    out.push(line);
  }
  return out;
}

/**
 * Draw `text` with its top-left at (x, y); `unit` is the size of one font
 * pixel in ctx units (already a whole number of native pixels). `visible(i)`
 * can hide characters (typewriter). Every rect lands on the pixel grid.
 */
export function draw(ctx, text, x, y, unit, fill, visible = null) {
  ctx.fillStyle = fill;
  let cx = x, i = 0;
  for (const ch of text) {
    const g = glyph(ch);
    if (!visible || visible(i)) {
      g.rows.forEach((row, ry) => row.forEach((on, rx) => { if (on) ctx.fillRect(cx + rx * unit, y + ry * unit, unit, unit); }));
    }
    cx += (g.w + 1) * unit;
    i++;
  }
}
